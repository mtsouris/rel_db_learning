# ── Module 05: Normalization ─────────────────────────────────────────────────
#
# Normalization specs are declared STANDALONE, without ``inherits_from``.
# Inheritance only ever *unions* requirements (see ``ExerciseSpec.resolve``),
# but normalization *removes* columns: First Normal Form takes the repeating
# ``book.authors`` and ``book.genres`` text out of ``book`` and relocates them
# into dedicated tables. A spec inheriting Stage 6 would keep requiring the
# removed columns and so could never describe the normalized schema. Each
# Module 05 spec therefore restates the full schema from scratch.


PROJECT_NORM_1NF = ExerciseSpec(
    title="Normalization: First Normal Form",
    description=(
        "Check that the Library is in First Normal Form. The book table no "
        "longer stores authors and genres as repeating, comma-separated text: "
        "those two columns are gone, replaced by the author and genre tables "
        "and the book_author and book_genre junction tables (each with a "
        "two-column primary key). Every other table from Stage 6 is unchanged."
    ),
    required_tables=[
        TableSpec(
            name="book",
            required_columns=[
                ColumnSpec("book_id", expected_type="integer", primary_key=True),
                ColumnSpec("title", expected_type="varchar"),
                # authors and genres are intentionally absent in 1NF: they move
                # to the author / genre tables through the junctions below.
                ColumnSpec("publisher_name", expected_type="varchar"),
                ColumnSpec("publisher_address", expected_type="varchar"),
                ColumnSpec("publisher_city", expected_type="varchar"),
                ColumnSpec("is_available", expected_type="boolean"),
            ],
        ),
        TableSpec(
            name="member",
            required_columns=[
                ColumnSpec("member_id", expected_type="integer", primary_key=True),
                ColumnSpec("full_name", expected_type="varchar"),
                ColumnSpec("address", expected_type="varchar"),
                ColumnSpec("city", expected_type="varchar"),
                ColumnSpec("country", expected_type="varchar"),
                ColumnSpec("penalty_days", expected_type="integer"),
                ColumnSpec("phone", expected_type="varchar"),
                ColumnSpec("email", expected_type="varchar"),
            ],
        ),
        TableSpec(
            name="loan",
            required_columns=[
                ColumnSpec("loan_id", expected_type="integer", primary_key=True),
                # book_id / member_id / librarian_id are omitted: they come
                # from the loan relationships declared below.
                ColumnSpec("loan_date", expected_type="date"),
                ColumnSpec("return_date", expected_type="date"),
                ColumnSpec("is_returned", expected_type="boolean"),
            ],
        ),
        TableSpec(
            name="member_card",
            required_columns=[
                ColumnSpec("card_id", expected_type="integer", primary_key=True),
                ColumnSpec("issue_date", expected_type="date"),
                ColumnSpec("expiry_date", expected_type="date"),
            ],
        ),
        TableSpec(
            name="reservation",
            required_columns=[
                ColumnSpec("reservation_id", expected_type="integer", primary_key=True),
                ColumnSpec("reservation_date", expected_type="date"),
                ColumnSpec("is_fulfilled", expected_type="boolean"),
            ],
        ),
        TableSpec(
            name="librarian",
            required_columns=[
                ColumnSpec("librarian_id", expected_type="integer", primary_key=True),
                ColumnSpec("full_name", expected_type="varchar"),
                ColumnSpec("hire_date", expected_type="date"),
                ColumnSpec("is_manager", expected_type="boolean"),
            ],
        ),
        TableSpec(
            name="book_copy",
            required_columns=[
                ColumnSpec("copy_id", expected_type="integer", primary_key=True),
                ColumnSpec("acquisition_date", expected_type="date"),
                ColumnSpec("condition", expected_type="varchar"),
            ],
        ),
        TableSpec(
            name="author",
            required_columns=[
                ColumnSpec("author_id", expected_type="integer", primary_key=True),
                ColumnSpec("name", expected_type="varchar"),
            ],
        ),
        TableSpec(
            name="genre",
            required_columns=[
                ColumnSpec("genre_id", expected_type="integer", primary_key=True),
                ColumnSpec("name", expected_type="varchar"),
            ],
        ),
        TableSpec(
            name="book_author",
            required_columns=[
                # Composite primary key. Unlike ordinary foreign-key columns,
                # which the spec omits, these two ARE the table's primary key,
                # so each carries primary_key=True and the pair is checked.
                ColumnSpec("book_id", expected_type="integer", primary_key=True),
                ColumnSpec("author_id", expected_type="integer", primary_key=True),
            ],
        ),
        TableSpec(
            name="book_genre",
            required_columns=[
                # Composite primary key, same pattern as book_author.
                ColumnSpec("book_id", expected_type="integer", primary_key=True),
                ColumnSpec("genre_id", expected_type="integer", primary_key=True),
            ],
        ),
    ],
    required_relationships=[
        # Carried over unchanged from Stage 6.
        RelationshipSpec(
            from_table="loan", to_table="book",
            cardinality="1:N",
            description="loan -> book",
        ),
        RelationshipSpec(
            from_table="loan", to_table="member",
            cardinality="1:N",
            description="loan -> member",
        ),
        RelationshipSpec(
            from_table="loan", to_table="librarian",
            cardinality="1:N",
            description="loan -> librarian",
        ),
        RelationshipSpec(
            from_table="member_card", to_table="member",
            cardinality="1:1",
            description="member_card -> member",
        ),
        RelationshipSpec(
            from_table="reservation", to_table="book",
            cardinality="1:N",
            description="reservation -> book",
        ),
        RelationshipSpec(
            from_table="reservation", to_table="member",
            cardinality="1:N",
            description="reservation -> member",
        ),
        RelationshipSpec(
            from_table="book_copy", to_table="book",
            cardinality="1:N",
            description="book_copy -> book",
        ),
        # New in 1NF: each junction table is many-to-one to its two parents.
        # In this spec's convention from_table is the "many" side (the FK
        # owner), so a many-to-one junction is expressed as cardinality 1:N.
        RelationshipSpec(
            from_table="book_author", to_table="book",
            cardinality="1:N",
            description="book_author -> book",
        ),
        RelationshipSpec(
            from_table="book_author", to_table="author",
            cardinality="1:N",
            description="book_author -> author",
        ),
        RelationshipSpec(
            from_table="book_genre", to_table="book",
            cardinality="1:N",
            description="book_genre -> book",
        ),
        RelationshipSpec(
            from_table="book_genre", to_table="genre",
            cardinality="1:N",
            description="book_genre -> genre",
        ),
    ],
)


